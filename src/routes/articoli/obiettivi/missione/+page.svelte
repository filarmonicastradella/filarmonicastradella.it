<section>
    <h2>Chi siamo</h2>
    <p>
        Portiamo il nome di uno dei grandi compositori del Seicento e quasi 250 anni di storia, e ne siamo orgogliosi. Ma non siamo un museo: la
        tradizione per noi è un punto di partenza, non un luogo in cui fermarsi. Ci interessano il presente e il futuro della musica in questo
        territorio.
    </p>
    <p>
        Oggi siamo più di 50 soci e più di 40 musicisti attivi, in quattro formazioni:
        <a href="/formazioni/stradella-facendo">Stradella Facendo</a>, la nostra orchestra di fiati; la
        <a href="/formazioni/streetella-band">Streetella Band</a>, la street band; l'<a href="/formazioni/orchestra-infieri">Orchestra Infieri</a>,
        dove archi e fiati suonano insieme; i <a href="/formazioni/filarmonici-dissonanti">Filarmonici Dissonanti</a>, il gruppo di musica antica.
        In Stradella Facendo e nella Streetella Band l'età media è sotto i 18 anni, e accanto ai più giovani suonano musicisti con decenni di
        esperienza. È così che una tradizione resta viva.
    </p>
    <p>
        Siamo un'associazione di promozione sociale autonoma, iscritta al RUNTS e affiliata ad ANBIMA, con gli scopi scritti all'articolo 2 dello
        <a href="/documents/statuto.pdf" type="application/pdf">statuto</a><sup><a href="#fonte-1" role="doc-noteref" id="rimando-1a" aria-label="Fonte 1">1</a></sup>, e lavoriamo con il sostegno del Comune di Fivizzano.
    </p>
</section>

<section>
    <h2>Perché siamo rinati</h2>
    <p>
        A Fivizzano e in Lunigiana tanti ragazzi imparano a suonare, e ci sono insegnanti preparati e giovani motivati. Molti però smettono quando
        finiscono di studiare, perché non trovano un posto dove continuare a fare musica insieme. La Filarmonica è stata rifondata per essere quel
        posto, aperto a ragazzi e adulti, a qualunque età, dove la musica diventa uno strumento di crescita personale e sociale.
    </p>
    <p>
        La nostra <a href="/articoli/storia/filarmonica">storia</a> ci ha insegnato quanto sia fragile una realtà musicale: dalla fine degli anni
        Novanta la Filarmonica è rimasta in silenzio per quasi trent'anni.<sup><a href="#fonte-4" role="doc-noteref" id="rimando-4a" aria-label="Fonte 4">4</a></sup> Per questo siamo ripartiti con un modello in cui la musica non dipende mai
        da una persona sola.
    </p>
</section>

<section>
    <h2>In cosa crediamo</h2>
    <p>
        La musica non è qualcosa da consumare, fatta da altri e portata da fuori per intrattenerci. È qualcosa che si fa, insieme, qui. Sul nostro
        palco ci sono studenti, lavoratori, pensionati, ragazzi del paese: gente che fa quello che può, e che lo fa con passione. Per questo la
        Filarmonica è al servizio di chi suona, e il concerto è il frutto di un percorso fatto insieme.
    </p>
    <p>
        Preferiamo far suonare cinquanta ragazzi del territorio che portare un grande nome da fuori. Un'iniziativa per noi è riuscita quando arriva
        chi di solito non arriva, e quando lascia le persone più capaci di fare da sé. Per lo stesso motivo la cosa peggiore che ci possa capitare è
        perdere un musicista: una prova andata male si recupera la settimana dopo, una persona che se ne va spesso non torna.
    </p>
    <p>
        Da noi i titoli di studio restano fuori dalla porta. La fiducia si guadagna sul campo, con il lavoro fatto insieme, e nessuno sta sul
        piedistallo. Facciamo musica con impegno ma senza perfezionismo, in un ambiente sereno dove ci si rispetta e si cresce insieme. Quando qualcosa
        non va cerchiamo il problema nel modo in cui ci organizziamo, non nelle persone.
    </p>
    <p>
        Siamo un'associazione, non un'accademia, e la partecipazione è libera. Non chiediamo un minimo di presenze: contiamo su ognuno quando può
        esserci, ai concerti, alle prove e nei momenti di vita associativa, perché la musica si fa insieme. Chi viene, viene perché ci sta bene. Tutto
        si regge sul volontariato: nessuno di noi è pagato per suonare, nemmeno chi dirige.
    </p>
</section>

<section>
    <h2>Una porta aperta</h2>
    <p>
        Per far parte della Filarmonica basta <a href="/associazione/iscrizione">iscriversi all'associazione</a>, con una quota annuale di 12 €.<sup><a href="#fonte-2" role="doc-noteref" id="rimando-2a" aria-label="Fonte 2">2</a></sup> Da
        soci si può chiedere di entrare nelle formazioni, ognuna con i propri requisiti: per Stradella Facendo, per esempio, bastano 14 anni e una
        formazione musicale di base, come quella della scuola media a indirizzo musicale. Si può far parte di più formazioni.
    </p>
    <p>
        Suonare costa, e chi suona da solo lo sa bene. Per questo l'associazione si fa carico di ciò che un musicista da solo difficilmente potrebbe
        sostenere: lo strumento, le parti e la cartoleria, la sala prove e il suo riscaldamento, l'impianto audio, i diritti SIAE e l'assicurazione.
        Mettendo insieme le risorse di tutti, ognuno può dedicarsi a suonare. E soprattutto offriamo ciò che nessuna quota può comprare: un gruppo di
        persone con cui fare musica.
    </p>
</section>

<section>
    <h2>Decidiamo insieme</h2>
    <p>
        Il repertorio nasce dai musicisti: i componenti propongono i brani e li votano in una graduatoria, e i direttori scelgono da lì cosa preparare
        per ogni stagione.
    </p>
    <p>
        I direttori sono più di uno e sono prima di tutto musicisti. Li indicano i componenti di ogni formazione, dai 14 anni in su, anche dopo averli
        visti guidare una prova, e il consiglio direttivo ne ratifica la nomina, che dura un anno. Allo stesso modo i componenti eleggono il comitato
        artistico e il comitato comunicazione, che sono gli organi che lavorano davvero ogni giorno. Ognuno dirige in autonomia i propri brani, e
        quando non dirige suona accanto agli altri. Le responsabilità sono distribuite, non accentrate.
    </p>
    <p>
        Anche il calendario si costruisce insieme. Ogni settimana i musicisti segnalano i propri impegni, e le prove di ogni formazione si fissano
        quando può esserci il maggior numero di persone, tenendo conto di chi suona in più gruppi.
    </p>
    <p>
        Le regole che ci siamo dati sono poche, semplici e scritte. Servono a ricordare come lavoriamo e a orientarci quando non siamo d'accordo; se la
        pratica cambia in meglio, le aggiorniamo. Statuto, contributi pubblici ricevuti e composizione del consiglio sono pubblici nella sezione
        <a href="/trasparenza">Amministrazione trasparente</a>.<sup><a href="#fonte-3" role="doc-noteref" id="rimando-3a" aria-label="Fonte 3">3</a></sup>
    </p>
</section>

<section>
    <h2>Si impara insieme</h2>
    <p>
        Ognuno ha il diritto di imparare e anche quello di insegnare. Chi sa di più accompagna chi sa di meno, e spesso il compagno che ha superato
        una difficoltà l'anno scorso è la persona migliore per spiegarla oggi. Chi insegna, intanto, impara a sua volta.
    </p>
    <p>
        I capi sezione, guidando i compagni, imparano passo dopo passo a dirigere e si guadagnano la fiducia di tutti. Il numero di direttori e capi
        sezione cresce insieme alle formazioni: se qualcuno è impedito o si ammala c'è sempre chi è pronto a prendere il suo posto, e una prova non
        salta mai perché manca qualcuno. Così la Filarmonica forma da sé le sue guide. La storia dei gruppi musicali dei nostri paesi lo insegna: dove
        tutto si concentra in poche mani, prima o poi la musica si spegne.
    </p>
</section>

<section>
    <h2>Al servizio del territorio</h2>
    <p>
        Suoniamo alle feste e alle cerimonie, negli ospedali e nelle RSA, e ogni stagione cerchiamo di portare la nostra musica anche in sale
        prestigiose. Ogni concerto richiama centinaia di persone: famiglie, amici, vicini, perché sul palco ci sono loro.
    </p>
    <p>
        Non svolgiamo servizi religiosi, ma non viviamo chiusi in noi stessi. Collaboriamo con le realtà musicali amiche della Lunigiana,
        le facciamo conoscere e mettiamo in contatto chi vuole suonare con chi ha bisogno di musicisti. Chi suona da noi può suonare anche con loro,
        e chi suona con uno strumento della Filarmonica può usarlo anche lì. Lo scambio e la contaminazione arricchiscono tutti: nessuna voce
        musicale del territorio deve spegnersi per mancanza di persone.
    </p>
</section>

<section>
    <h2>Dove vogliamo arrivare</h2>
    <p>
        Sogniamo una Filarmonica con più musicisti e più giovani, e una rete di realtà musicali della Lunigiana che collaborino e si sostengano a
        vicenda: una comunità in cui suonare sia normale, alla portata di tutti, e in cui ogni euro e ogni ora investiti restino qui, nelle persone.
    </p>
    <p>
        Per questo misuriamo il nostro lavoro da quanti ragazzi suonano in Lunigiana, con noi o con qualsiasi altra realtà musicale, più che da
        quanto cresce la Filarmonica. Vogliamo arrivare anche nelle frazioni e nelle valli dove oggi un ragazzo che vuole suonare non ha un posto vicino a casa.
    </p>
</section>

