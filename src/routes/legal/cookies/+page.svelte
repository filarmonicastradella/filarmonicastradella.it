            <h1>Politica sui Cookie</h1>
            <p>Questo sito web utilizza i cookie per garantire il corretto funzionamento delle procedure e migliorare l'esperienza di navigazione degli utenti. Il presente documento fornisce informazioni dettagliate sull'uso dei cookie, su come vengono gestiti e sulle modalità per disabilitarli.</p>
        </header>

        <section>
            <h2>1. Cosa sono i Cookie</h2>
            <p>I cookie sono piccoli file di testo che i siti visitati dagli utenti inviano ai loro terminali, ove vengono memorizzati per essere poi ritrasmessi agli stessi siti alla visita successiva. I cookie di prima parte sono impostati direttamente dal gestore del sito web, mentre i cookie di terze parti sono impostati da un dominio diverso da quello visitato dall'utente.</p>
        </section>

        <section>
            <h2>2. Tipologie di Cookie Utilizzate</h2>
            <p>Il sito della Filarmonica Alessandro Stradella APS fa uso esclusivamente di cookie tecnici necessari al funzionamento della piattaforma:</p>
            <ul>
                <li><strong>Cookie tecnici di navigazione o di sessione:</strong> Garantiscono la normale navigazione e fruizione del sito web, permettendo ad esempio di autenticarsi o di memorizzare preferenze di visualizzazione (come la modalità scura o chiara).</li>
                <li><strong>Cookie analitici (assimilati ai tecnici):</strong> Utilizzati direttamente dal gestore del sito per raccogliere informazioni, in forma aggregata e anonima, sul numero degli utenti e su come questi visitano il sito stesso, al solo fine di ottimizzarne le prestazioni.</li>
            </ul>
            <p>Non vengono utilizzati in alcun modo cookie di profilazione per finalità promozionali o di marketing, né cookie di tracciamento di terze parti per scopi pubblicitari.</p>
        </section>

        <section>
            <h2>3. Gestione dei Cookie tramite il Browser</h2>
            <p>L'utente può decidere se accettare o meno i cookie utilizzando le impostazioni del proprio browser. La disabilitazione dei cookie tecnici potrebbe tuttavia compromettere la piena fruibilità di alcune funzionalità del sito. Di seguito vengono indicati i collegamenti alle guide dei principali browser per la gestione dei cookie:</p>
            <ul>
                <li><strong>Google Chrome:</strong> Gestione delle impostazioni di navigazione e privacy.</li>
                <li><strong>Mozilla Firefox:</strong> Gestione dei pannelli protezione e dati personali.</li>
                <li><strong>Apple Safari:</strong> Gestione di cookie e dati dei siti web.</li>
                <li><strong>Microsoft Edge:</strong> Gestione delle autorizzazioni per i siti.</li>
            </ul>
        </section>

