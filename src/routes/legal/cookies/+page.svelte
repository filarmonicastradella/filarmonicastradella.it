            <h1>Politica sui cookie</h1>
            <p>Questo sito non imposta cookie propri, non usa strumenti di analisi statistica e non profila i visitatori.</p>
            <p>Informativa sull'uso dei cookie, ai sensi del Provvedimento del Garante per la protezione dei dati personali n. 231 del 10 giugno 2021</p>
        </header>

        <section aria-labelledby="cosa-heading">
            <h2 id="cosa-heading">1. Cosa sono i cookie</h2>
            <p>I cookie sono piccoli file di testo che un sito invia al browser, che li memorizza e li rinvia alla visita successiva. I cookie di terze parti sono impostati da un dominio diverso da quello del sito che stai visitando.</p>
        </section>

        <section aria-labelledby="usati-heading">
            <h2 id="usati-heading">2. Cookie usati da questo sito</h2>
            <p>Il sito non imposta alcun cookie né altri dati nel tuo browser, tecnici o di altro tipo. Per questo non mostra un banner di consenso.</p>
        </section>

        <section aria-labelledby="terze-heading">
            <h2 id="terze-heading">3. Servizi di terze parti</h2>
            <p>Alcune parti del sito caricano contenuti da servizi esterni: le foto e i video della galleria (Instagram e Behold) e, solo se scegli di mostrarle, le mappe (Google Maps). Questi servizi ricevono il tuo indirizzo IP e potrebbero impostare propri cookie, secondo le loro politiche:</p>
            <ul>
                <li><a href="https://policies.google.com/technologies/cookies?hl=it" target="_blank" rel="noopener noreferrer">Cookie di Google</a></li>
                <li><a href="https://www.instagram.com/legal/cookies/" target="_blank" rel="noopener noreferrer">Cookie di Instagram</a></li>
            </ul>
            <p>Le mappe non si caricano finché non lo chiedi tu, con il pulsante dedicato. In alternativa puoi aprirle direttamente su Google Maps con il link sotto ogni mappa.</p>
        </section>

        <section aria-labelledby="browser-heading">
