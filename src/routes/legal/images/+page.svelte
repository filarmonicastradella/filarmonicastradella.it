<header>
    <h1>Liberatoria per immagini, voce ed esecuzioni</h1>
    <p>Durante prove e concerti scattiamo foto e facciamo riprese. Qui trovi come le usiamo e cosa puoi scegliere.</p>
</header>

<section>
    <h2>Cosa autorizzi</h2>
    <p>
        Autorizzi la {organization.name} a fotografare e a registrare in audio e video la tua immagine, la tua voce e le tue esecuzioni musicali, da solo o
        insieme agli altri, durante prove, concerti, rassegne, trasferte e le altre attività dell'associazione.
    </p>
    <p>
        L'uso è gratuito, solo per documentare e far conoscere le attività dell'associazione, e vale finché non lo revochi. È un consenso separato
        dall'iscrizione: se non lo dai, partecipi alle attività esattamente come gli altri.
    </p>
</section>

<section>
    <h2>Dove possono essere usate</h2>
    <p>Scegli canale per canale: puoi acconsentire ad alcuni e non ad altri.</p>
    <ul>
        <li>Archivio interno e documentazione delle attività</li>
        <li>Sito internet dell'associazione</li>
        <li>Canali social ufficiali dell'associazione</li>
        <li>Materiale a stampa (locandine, programmi di sala) e comunicazioni alla stampa</li>
        <li>Registrazioni audio e video dei concerti su piattaforme di condivisione</li>
        <li>Documentazione dei progetti per enti finanziatori, scuole e pubbliche amministrazioni</li>
    </ul>
</section>

<section>
    <h2>I nostri impegni</h2>
    <ul>
        <li>Non cediamo foto e registrazioni ad altri e non le usiamo per guadagnare.</li>
        <li>Non le usiamo mai in contesti che possano offendere la dignità o il decoro di chi è ritratto.</li>
        <li>Se un giorno volessimo realizzare dischi o video da vendere, anche per autofinanziarci, ti chiederemo un'autorizzazione a parte.</li>
        <li>Le foto e le riprese fatte da familiari o spettatori durante gli eventi pubblici non sono nostre e non ne rispondiamo.</li>
    </ul>
</section>

<section>
    <h2>Per i minori</h2>
    <p>
        Per chi ha meno di 18 anni decidono i genitori o il tutore, d'intesa tra loro; chi ha già compiuto 14 anni ne prende visione insieme a loro. Nelle
        pubblicazioni del minore compare al massimo il nome proprio, salvo i programmi di sala, e non pubblichiamo mai immagini riprese negli spogliatoi o
        mentre ci si cambia.
    </p>
</section>

<section>
    <h2>Come revocare</h2>
    <p>
        Puoi revocare il consenso quando vuoi, in tutto o solo per alcuni canali, scrivendo a
        <a href="mailto:privacy@filarmonicastradella.it">privacy@filarmonicastradella.it</a>. Entro 30 giorni togliamo i contenuti dai canali digitali che
        gestiamo; il materiale a stampa già distribuito resta com'è. Se sei in una ripresa di gruppo che non si può togliere senza danneggiare gli altri,
        ti rendiamo non riconoscibile.
    </p>
    <p>Il consenso dato prima della revoca resta valido per gli usi già fatti. Per tutto il resto vale l'<a href="/legal/privacy">informativa privacy</a>.</p>
</section>

