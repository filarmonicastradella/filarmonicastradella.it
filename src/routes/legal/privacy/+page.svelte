        <section>
            <h2>2. Tipologia di Dati Trattati e Finalità</h2>
            <p>I trattamenti dei dati personali effettuati sono finalizzati esclusivamente al perseguimento degli scopi istituzionali dell'associazione di promozione sociale, e in particolare:</p>
            <ul>
                <li><strong>Dati di navigazione:</strong> I sistemi informatici e le procedure software preposte al funzionamento di questo sito acquisiscono, nel corso del loro normale esercizio, alcuni dati personali la cui trasmissione è implicita nell'uso dei protocolli di comunicazione di Internet (indirizzi IP, URI delle risorse richieste, orario della richiesta). Tali dati vengono utilizzati al solo fine di ricavare informazioni statistiche anonime sull'uso del sito e per controllarne il corretto funzionamento.</li>
                <li><strong>Dati forniti volontariamente dall'utente:</strong> L'invio facoltativo ed esplicito di comunicazioni tramite i moduli di contatto presenti sul sito o via e-mail agli indirizzi indicati comporta la successiva acquisizione dei dati personali forniti (a titolo esplicito nome, cognome e indirizzo di posta elettronica), necessari per rispondere alle richieste formulate.</li>
            </ul>
        </section>

        <section>
            <h2>3. Base Giuridica del Trattamento</h2>
            <p>Il trattamento dei dati personali si fonda sul consenso espresso dall'utente all'invio delle richieste, nonché sulla necessità di adempiere a obblighi di legge cui è soggetta l'associazione o per l'esecuzione di compiti di interesse pubblico connessi alle attività statutarie della Filarmonica.</p>
        </section>

        <section>
            <h2>4. Modalità di Trattamento e Conservazione</h2>
            <p>I dati personali sono trattati con strumenti informatici e telematici per il tempo strettamente necessario a conseguire gli scopi per cui sono stati raccolti. Specifiche misure di sicurezza sono osservate per prevenire la perdita dei dati, usi illeciti o non corretti e accessi non autorizzati.</p>
        </section>

        <section>
            <h2>5. Diritti degli Interessati</h2>
            <p>Gli utenti a cui si riferiscono i dati personali hanno il diritto in qualunque momento di ottenere la conferma dell'esistenza o meno dei medesimi dati, di conoscerne il contenuto e l'origine, verificarne l'esattezza o chiederne l'integrazione, l'aggiornamento, oppure la rettificazione (Artt. 15 e seguenti del GDPR). Le richieste vanno rivolte direttamente al Titolare del trattamento presso i recapiti ufficiali dell'associazione.</p>
