<dl itemscope itemtype="https://schema.org/FAQPage">
    <div itemscope itemprop="mainEntity" itemtype="https://schema.org/Question">
        <dt itemprop="name">Come si suona con la Filarmonica?</dt>
        <dd itemprop="acceptedAnswer" itemscope itemtype="https://schema.org/Answer">
            <span itemprop="text">
                Prima ci si iscrive come soci dell'associazione con la <a href="/support/join">richiesta di iscrizione</a>, poi si chiede di entrare nell'ensemble in cui si vuole suonare.
            </span>
        </dd>
    </div>

    <div itemscope itemprop="mainEntity" itemtype="https://schema.org/Question">
        <dt itemprop="name">Quali ensemble ci sono?</dt>
        <dd itemprop="acceptedAnswer" itemscope itemtype="https://schema.org/Answer">
            <span itemprop="text">
                Stradella Facendo, Streetella Band, Infieri e Filarmonici Dissonanti: le presentiamo nella pagina <a href="/ensembles">Ensemble</a>.
            </span>
        </dd>
    </div>

    <div itemscope itemprop="mainEntity" itemtype="https://schema.org/Question">
        <dt itemprop="name">Posso iscrivermi se sono minorenne?</dt>
        <dd itemprop="acceptedAnswer" itemscope itemtype="https://schema.org/Answer">
            <span itemprop="text">
                Sì: per i minorenni la richiesta di iscrizione può essere fatta online da un genitore o da un tutore, compilando lo stesso <a href="/support/join">modulo</a>.
            </span>
        </dd>
    </div>

    <div itemscope itemprop="mainEntity" itemtype="https://schema.org/Question">
        <dt itemprop="name">Dove vi trovo?</dt>
        <dd itemprop="acceptedAnswer" itemscope itemtype="https://schema.org/Answer">
            <span itemprop="text">
                Abbiamo due sedi, a Fivizzano e a Serricciolo: indirizzi e mappe sono nella pagina <a href="/about/locations">Le nostre sedi</a>. I concerti e gli altri appuntamenti pubblici sono nella pagina <a href="/events">Eventi</a>.
            </span>
        </dd>
    </div>

    <div itemscope itemprop="mainEntity" itemtype="https://schema.org/Question">
        <dt itemprop="name">Come posso sostenere l'associazione?</dt>
        <dd itemprop="acceptedAnswer" itemscope itemtype="https://schema.org/Answer">
            <span itemprop="text">
                Iscrivendoti come socio o con una <a href="/support/donate">erogazione liberale</a> (il 5x1000 verrà aggiunto quando saremo beneficiari). Tutte le possibilità sono nella pagina <a href="/support">Sostienici</a>.
            </span>
        </dd>
    </div>

    <div itemscope itemprop="mainEntity" itemtype="https://schema.org/Question">
        <dt itemprop="name">Come ottengo la ricevuta di una donazione?</dt>
        <dd itemprop="acceptedAnswer" itemscope itemtype="https://schema.org/Answer">
            <span itemprop="text">
                Rilasciamo una ricevuta a chi dona: si richiede al tesoriere scrivendo a <a href="mailto:tesoreria@filarmonicastradella.it">tesoreria@filarmonicastradella.it</a>.
            </span>
        </dd>
    </div>

    <div itemscope itemprop="mainEntity" itemtype="https://schema.org/Question">
        <dt itemprop="name">Dove trovo i corsi di musica?</dt>
        <dd itemprop="acceptedAnswer" itemscope itemtype="https://schema.org/Answer">
            <span itemprop="text">
