<header>
    <h1>La nostra missione</h1>
    <p>
        La Filarmonica Alessandro Stradella suona a Fivizzano dal 1777. Siamo un'associazione di musicisti volontari, ragazzi e adulti insieme, che fa
        musica per chi la suona e per il proprio territorio.
    </p>
    <p><em>Custodi della tradizione, interpreti del futuro.</em></p>
</header>

<section>
    <h2>Chi siamo</h2>
    <p>
        Portiamo il nome di uno dei grandi compositori del Seicento e quasi 250 anni di storia, ma non siamo un museo: la tradizione per noi è un punto di
        partenza, non un luogo in cui fermarsi. Oggi siamo più di 50 soci e più di 40 musicisti attivi, in quattro formazioni:
        <a href="/about/ensembles/stradella-facendo">Stradella Facendo</a>, la nostra orchestra di fiati; la
        <a href="/about/ensembles/streetella-band">Streetella Band</a>; l'<a href="/about/ensembles/orchestra-infieri">Orchestra Infieri</a>; i
        <a href="/about/ensembles/filarmonici-dissonanti">Filarmonici Dissonanti</a>. In Stradella Facendo e nella Streetella Band l'età media è sotto i
        18 anni, e accanto ai più giovani suonano musicisti con decenni di esperienza. Siamo un'associazione di promozione sociale autonoma, iscritta al
        RUNTS e affiliata ad ANBIMA, con gli scopi scritti all'articolo 2 dello <a href="/documents/statuto.pdf" type="application/pdf">statuto</a>, e lavoriamo
        con il sostegno del Comune di Fivizzano.
    </p>
    <p>
        Nel nostro territorio ci sono insegnanti qualificati e giovani motivati, ma molti ragazzi che hanno studiato uno strumento smettono di suonare
        perché non trovano un luogo dove continuare. La Filarmonica è stata rifondata per essere quel luogo, aperto a ragazzi e adulti insieme, dove la
        musica diventa uno strumento di crescita personale e sociale. La nostra <a href="/articles/history/filarmonica">storia</a> ci ha insegnato quanto questo sia
        fragile: dalla fine degli anni Novanta la Filarmonica è rimasta in silenzio per quasi trent'anni. Per questo siamo ripartiti con un modello in cui
        la musica non dipende mai da una persona sola.
    </p>
</section>

<section>
    <h2>In cosa crediamo</h2>
    <p>
        La musica non è qualcosa da consumare, fatta da altri e portata da fuori per intrattenerci: è qualcosa che si fa, insieme, qui. Sul nostro palco
        ci sono studenti, lavoratori, pensionati, ragazzi del paese: gente che fa quello che può, e che lo fa con passione. Per questo la Filarmonica è al
        servizio di chi suona, e il concerto non è il fine ma il frutto di un percorso fatto insieme.
    </p>
    <p>
        Da noi i titoli di studio restano fuori dalla porta. Facciamo musica con impegno ma senza perfezionismo, in un ambiente sereno dove ci si
        rispetta e si cresce insieme: chi sa di più accompagna chi sa di meno, e ognuno ha il diritto di imparare e anche quello di insegnare. Quando
        qualcosa non va cerchiamo il problema nel modo in cui ci organizziamo, non nelle persone; per questo ci siamo dati regole semplici, trasparenti e
        condivise.
    </p>
    <p>
        Siamo un'associazione, non un'accademia. Non chiediamo un minimo di presenze: contiamo su ognuno quando può esserci, ai concerti, alle prove
        e nei momenti di vita associativa, perché la musica si fa insieme. Ognuno dà qualcosa, e insieme teniamo in piedi qualcosa che appartiene a tutti. Tutto si regge sul
        volontariato: nessuno di noi è pagato per suonare, nemmeno chi dirige.
    </p>
</section>

<section>
    <h2>Come funziona</h2>
    <p>
        Per far parte della Filarmonica basta <a href="/support/join">iscriversi all'associazione</a>, con una quota annuale di 12 €; da soci si può
        chiedere di entrare nelle formazioni, ognuna con i propri requisiti. L'associazione si fa carico di ciò che un musicista da solo difficilmente
        potrebbe sostenere, dallo strumento alla sala prove, così ognuno può dedicarsi a ciò che conta: suonare. E soprattutto offriamo ciò che nessuna
        quota può comprare: un gruppo di persone con cui fare musica.
    </p>
    <p>
        Il repertorio nasce dai musicisti: i componenti propongono i brani e li votano in una graduatoria, e i direttori scelgono da lì cosa preparare
        per ogni stagione. I direttori sono più di uno e sono prima di tutto musicisti. Li indicano i componenti di ogni formazione, dai 14 anni in su, anche
        dopo averli visti guidare una prova, e il consiglio direttivo ne ratifica la nomina, che dura un anno. Allo stesso modo i componenti eleggono
        il comitato artistico e il comitato comunicazione. Ognuno dirige in autonomia i propri brani, e quando non dirige suona
        accanto agli altri. Anche le prove si fissano insieme, ogni settimana, quando può esserci il maggior numero di persone. I
        capi sezione, guidando i compagni, imparano passo dopo passo a dirigere: così la Filarmonica forma da sé le sue guide, e una prova non salta mai
        perché manca qualcuno.
    </p>
</section>

<section>
    <h2>Al servizio del territorio</h2>
    <p>
        Suoniamo alle feste e alle cerimonie, negli ospedali e nelle RSA, e ogni stagione cerchiamo di portare la nostra musica anche in sale
        prestigiose. Ogni concerto richiama centinaia di persone: famiglie, amici, vicini, perché sul palco ci sono loro. Non svolgiamo servizi
        religiosi, ma collaboriamo con le realtà musicali amiche della Lunigiana, le facciamo conoscere e mettiamo in contatto chi vuole suonare con chi
        ha bisogno di musicisti: chi suona con uno strumento della Filarmonica può usarlo anche con loro.
    </p>
    <p>
        Sogniamo una Filarmonica con più musicisti e più giovani, e una rete di realtà musicali della Lunigiana che collaborino e si sostengano a
        vicenda: una comunità in cui suonare sia normale, alla portata di tutti, e in cui ogni euro e ogni ora investiti restino qui, nelle persone.
    </p>
</section>

